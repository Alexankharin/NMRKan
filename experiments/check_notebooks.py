"""Execute supported notebooks in isolated Python kernels."""

import argparse
import os
from pathlib import Path

import nbformat
from nbclient import NotebookClient


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=root / "outputs/executed_notebooks"
    )
    parser.add_argument(
        "--paper-runs",
        type=Path,
        help="Completed full paper runs to display in the notebooks.",
    )
    parser.add_argument(
        "--molecular-reports",
        type=Path,
        help="Also execute the three reports generated by experiments.molecules.",
    )
    parser.add_argument(
        "--in-place",
        action="store_true",
        help="Also save executed outputs in notebooks/ after all notebooks succeed.",
    )
    args = parser.parse_args()
    output = args.output.resolve()
    if args.paper_runs:
        os.environ["NMRKAN_PAPER_RUNS"] = str(args.paper_runs.resolve())
    if args.molecular_reports:
        os.environ["NMRKAN_MOLECULE_OUTPUT"] = str(args.molecular_reports.resolve())
    output.mkdir(parents=True, exist_ok=True)
    # Keep runtime files inside the checkout rather than the user's home.
    for key, name in (
        ("JUPYTER_RUNTIME_DIR", "runtime"),
        ("IPYTHONDIR", "ipython"),
        ("MPLCONFIGDIR", "matplotlib"),
    ):
        folder = output / name
        folder.mkdir(exist_ok=True)
        os.environ.setdefault(key, str(folder))
    os.environ.setdefault("MPLBACKEND", "Agg")
    paths = [
        (path, output / path.name, path.parent)
        for path in sorted((root / "notebooks").glob("[0-9][0-9]_*.ipynb"))
    ]
    if args.molecular_reports:
        report_output = output / "molecular_reports"
        report_output.mkdir(exist_ok=True)
        for name in (
            "dss_analysis.ipynb",
            "dss_asn_comparison.ipynb",
            "homotaurine_asn_comparison.ipynb",
        ):
            path = args.molecular_reports.resolve() / name
            if not path.is_file():
                parser.error(f"Missing report {path}; rebuild the reports first.")
            paths.append((path, report_output / name, root))
    completed = []
    for path, target, working_directory in paths:
        notebook = nbformat.read(path, as_version=4)
        nbformat.validate(notebook)
        print(f"Executing {path.name}", flush=True)
        NotebookClient(
            notebook,
            timeout=300,
            kernel_name="python3",
            resources={"metadata": {"path": str(working_directory)}},
        ).execute()
        nbformat.write(notebook, target)
        if path.parent == root / "notebooks":
            completed.append((path, notebook))
    if args.in_place:
        for path, notebook in completed:
            nbformat.write(notebook, path)
        print("Saved executed outputs in notebooks/.")
    print(f"Executed notebooks: {output}")


if __name__ == "__main__":
    main()
